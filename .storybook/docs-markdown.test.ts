import { describe, expect, test } from 'vitest';

import { pageSummary, splitGuide, stripStoryMarkers } from './docs-markdown';

const guide = `# Modals

Confirmations and errors.

## Confirmation modal

Intro.

<!-- story: ConfirmationModal -->

The flow.
`;

const shape = (markdown: string) =>
  splitGuide(markdown).map((part) =>
    part.type === 'story' ? `story:${part.story}` : part.markdown.trim(),
  );

describe('splitGuide', () => {
  test('splits Markdown around story markers', () => {
    expect(shape(guide)).toEqual([
      '# Modals\n\nConfirmations and errors.\n\n## Confirmation modal\n\nIntro.',
      'story:ConfirmationModal',
      'The flow.',
    ]);
  });

  test('returns one Markdown part when there are no markers', () => {
    expect(splitGuide('# Theme\n\nTokens.\n')).toEqual([
      { type: 'markdown', markdown: '# Theme\n\nTokens.\n' },
    ]);
  });

  test('leaves markers inside fenced code blocks alone', () => {
    const markdown =
      'Mark an example like this:\n\n```md\n<!-- story: Example -->\n```\n\n~~~\n<!-- story: Other -->\n~~~\n';
    expect(shape(markdown)).toEqual([markdown.trim()]);
  });

  test('reads markers with Windows line endings', () => {
    expect(
      shape('Intro.\r\n\r\n<!-- story: Example -->\r\n\r\nMore.\r\n'),
    ).toEqual(['Intro.', 'story:Example', 'More.']);
  });

  test('reads a marker on the last line without a trailing newline', () => {
    expect(shape('Intro.\n\n<!-- story: Example -->')).toEqual([
      'Intro.',
      'story:Example',
    ]);
  });
});

describe('stripStoryMarkers', () => {
  test('removes marker lines and keeps one blank line between paragraphs', () => {
    expect(stripStoryMarkers(guide)).toContain('Intro.\n\nThe flow.\n');
  });

  test('removes a marker on the last line', () => {
    expect(stripStoryMarkers('Intro.\n\n<!-- story: Example -->')).toBe(
      'Intro.\n',
    );
  });

  test('keeps markers shown inside code blocks', () => {
    expect(stripStoryMarkers('```md\n<!-- story: Example -->\n```\n')).toBe(
      '```md\n<!-- story: Example -->\n```\n',
    );
  });
});

describe('pageSummary', () => {
  test('reads the title and first paragraph', () => {
    expect(pageSummary(guide)).toEqual({
      name: 'Modals',
      description: 'Confirmations and errors.',
    });
  });

  test('skips a generated banner and joins wrapped lines', () => {
    expect(
      pageSummary(
        '<!-- Generated by `pnpm stories:generate-docs`. Do not edit. -->\n\n# Button\n\nTriggers\nan action.\n\n## Usage\n',
      ),
    ).toEqual({ name: 'Button', description: 'Triggers an action.' });
  });

  test('reads a final paragraph with a single trailing newline', () => {
    expect(pageSummary('# Tag\n\nA metadata label.\n')).toEqual({
      name: 'Tag',
      description: 'A metadata label.',
    });
  });

  test('returns no description when the page starts with a heading or table', () => {
    expect(pageSummary('# Button\n\n## Usage\n\nText.\n')).toEqual({
      name: 'Button',
      description: '',
    });
    expect(pageSummary('# Slots\n\n| a | b |\n| - | - |\n').description).toBe(
      '',
    );
  });

  test('handles a page that is only a title', () => {
    expect(pageSummary('# Empty')).toEqual({ name: 'Empty', description: '' });
  });
});
