export type GuidePart =
  | { type: 'markdown'; markdown: string }
  | { type: 'story'; story: string };

const fenceLine = /^\s*(`{3,}|~{3,})/;
const storyMarkerLine = /^<!-- story: (\w+) -->\s*$/;

export function splitGuide(markdown: string): GuidePart[] {
  const parts: GuidePart[] = [];
  let lines: string[] = [];
  let fence: string | undefined;

  const flush = () => {
    const text = lines.join('\n');
    if (text.trim()) parts.push({ type: 'markdown', markdown: text });
    lines = [];
  };

  for (const line of markdown.split('\n')) {
    const fenceMatch = line.match(fenceLine);
    if (fenceMatch) {
      const marker = fenceMatch[1];
      if (!fence) fence = marker;
      else if (marker[0] === fence[0] && marker.length >= fence.length) {
        fence = undefined;
      }
    }
    const story = fence || fenceMatch ? null : line.match(storyMarkerLine);
    if (story) {
      flush();
      parts.push({ type: 'story', story: story[1] });
    } else {
      lines.push(line);
    }
  }
  flush();
  return parts;
}

export const stripStoryMarkers = (markdown: string): string =>
  splitGuide(markdown)
    .flatMap((part) =>
      part.type === 'markdown'
        ? [part.markdown.replace(/^(\r?\n)+/, '').trimEnd()]
        : [],
    )
    .join('\n\n')
    .concat('\n');

export const generatedBannerPrefix =
  '<!-- Generated by `pnpm stories:generate-docs`';

export const stripGeneratedBanner = (markdown: string): string =>
  markdown.replace(/^<!--[\s\S]*?-->\s*/, '');

const notProse = /^(#|\||```|<!--|>|- |\d+\. )/;

export function pageSummary(markdown: string): {
  name?: string;
  description: string;
} {
  const body = stripGeneratedBanner(markdown);
  const title = body.match(/^# (.+)(?:\n|$)/);
  const rest = title ? body.slice(title[0].length) : body;
  const [firstBlock = ''] = rest
    .split(/\n\s*\n/)
    .map((block) => block.trim())
    .filter(Boolean);
  return {
    name: title?.[1].trim(),
    description: notProse.test(firstBlock)
      ? ''
      : firstBlock.replace(/\s+/g, ' '),
  };
}
