import { execFileSync } from 'node:child_process';
import {
  existsSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { createServer, type Server } from 'node:http';
import type { AddressInfo } from 'node:net';
import {
  basename,
  extname,
  join,
  normalize,
  relative,
  resolve,
  sep,
} from 'node:path';

import { chromium } from '@playwright/test';
import { format, resolveConfig } from 'prettier';
import type { StrictArgTypes } from 'storybook/internal/types';
import { filterArgTypes } from 'storybook/preview-api';

import { getProjectRoot } from './get-project-root';
import { pageMarkdown } from '../.storybook/blocks/page-markdown';

type IndexEntry = {
  id: string;
  title: string;
  type: 'story' | 'docs';
  importPath: string;
};

type ComponentDocs = {
  description?: string;
  usage?: string;
  argTypes: StrictArgTypes;
  include?: string[] | RegExp;
  exclude?: string[] | RegExp;
};

const root = getProjectRoot();
const ioDirectory = join(root, 'src', 'lib', 'io');
const staticDirFlag = '--static-dir=';
const staticDirectory = resolve(
  root,
  process.argv
    .find((arg) => arg.startsWith(staticDirFlag))
    ?.slice(staticDirFlag.length) ?? 'storybook-static',
);
const check = process.argv.includes('--check');
const stage = process.argv.includes('--stage');
const storiesSuffix = '.stories.svelte';

const contentTypes: Record<string, string> = {
  '.css': 'text/css',
  '.html': 'text/html',
  '.js': 'text/javascript',
  '.json': 'application/json',
  '.mjs': 'text/javascript',
  '.svg': 'image/svg+xml',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
};

const bannerPrefix = '<!-- Generated by `pnpm stories:generate-docs`';

const banner = (storiesFile: string) =>
  `${bannerPrefix} from ${storiesFile.replace(storiesSuffix, '.usage.md')} and ${storiesFile}. Do not edit. -->\n\n`;

function serve(directory: string): Promise<Server> {
  const server = createServer((request, response) => {
    const pathname = decodeURIComponent(
      new URL(request.url ?? '/', 'http://localhost').pathname,
    );
    const filePath = normalize(join(directory, pathname));
    try {
      if (
        !filePath.startsWith(`${directory}${sep}`) ||
        !statSync(filePath).isFile()
      ) {
        response.writeHead(404).end();
        return;
      }
      response
        .writeHead(200, {
          'Content-Type':
            contentTypes[extname(filePath)] ?? 'application/octet-stream',
        })
        .end(readFileSync(filePath));
    } catch {
      response.writeHead(404).end();
    }
  });
  return new Promise((done) =>
    server.listen(0, '127.0.0.1', () => done(server)),
  );
}

function generatedFiles(directory = ioDirectory): string[] {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return generatedFiles(path);
    return entry.name.endsWith('.md') &&
      !entry.name.endsWith('.usage.md') &&
      readFileSync(path, 'utf8').startsWith(bannerPrefix)
      ? [relative(root, path)]
      : [];
  });
}

async function main() {
  if (!existsSync(join(staticDirectory, 'iframe.html'))) {
    throw new Error(
      `No Storybook build at ${relative(root, staticDirectory)}. Run \`pnpm stories:generate-docs\`, which builds Storybook first.`,
    );
  }

  const server = await serve(staticDirectory);
  const origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  const browser = await chromium.launch();

  try {
    const index: { entries: Record<string, IndexEntry> } = await (
      await fetch(`${origin}/index.json`)
    ).json();
    const stories = new Map<string, IndexEntry>();
    for (const entry of Object.values(index.entries)) {
      if (
        entry.type === 'story' &&
        entry.importPath.startsWith('./src/lib/io/') &&
        entry.importPath.endsWith(storiesSuffix) &&
        !stories.has(entry.importPath)
      ) {
        stories.set(entry.importPath, entry);
      }
    }

    const page = await browser.newPage();
    await page.addInitScript({ content: 'window.__name = (fn) => fn;' });
    await page.goto(`${origin}/iframe.html`);
    await page.waitForFunction(() => '__STORYBOOK_PREVIEW__' in window);

    const prettierOptions = await resolveConfig(join(ioDirectory, 'docs.md'));
    const stale: string[] = [];
    const outputs: string[] = [];
    let generated = 0;
    for (const story of stories.values()) {
      const docs = await page.evaluate(
        async (storyId): Promise<ComponentDocs> => {
          const preview = (
            window as unknown as {
              __STORYBOOK_PREVIEW__: {
                ready(): Promise<void>;
                storyStoreValue: {
                  loadCSFFileByStoryId(id: string): Promise<unknown>;
                  preparedMetaFromCSFFile(input: { csfFile: unknown }): {
                    argTypes: StrictArgTypes;
                    parameters: {
                      docs?: {
                        description?: { component?: string };
                        usage?: string;
                        argTypes?: Pick<ComponentDocs, 'include' | 'exclude'>;
                      };
                    };
                  };
                };
              };
            }
          ).__STORYBOOK_PREVIEW__;
          await preview.ready();
          const store = preview.storyStoreValue;
          const csfFile = await store.loadCSFFileByStoryId(storyId);
          const { argTypes, parameters } = store.preparedMetaFromCSFFile({
            csfFile,
          });

          return {
            ...parameters.docs?.argTypes,
            description: parameters.docs?.description?.component,
            usage: parameters.docs?.usage,
            argTypes: Object.fromEntries(
              Object.entries(argTypes).map(([key, arg]) => [
                key,
                {
                  name: arg.name,
                  description: arg.description,
                  type: arg.type && {
                    name: arg.type.name,
                    required: arg.type.required,
                  },
                  table: arg.table && {
                    type: arg.table.type,
                    defaultValue: arg.table.defaultValue,
                    disable: arg.table.disable,
                  },
                },
              ]),
            ) as StrictArgTypes,
          };
        },
        story.id,
      );
      if (!docs.usage) continue;
      generated += 1;

      const storiesPath = join(root, story.importPath);
      const markdownPath = `${storiesPath.slice(0, -storiesSuffix.length)}.md`;
      const markdown = await format(
        banner(basename(storiesPath)) +
          pageMarkdown({
            title: story.title.split('/').at(-1) ?? story.title,
            description: docs.description,
            usage: docs.usage,
            argTypes: filterArgTypes(docs.argTypes, docs.include, docs.exclude),
          }),
        { ...prettierOptions, filepath: markdownPath },
      );
      outputs.push(relative(root, markdownPath));
      const current = existsSync(markdownPath)
        ? readFileSync(markdownPath, 'utf8')
        : undefined;
      if (markdown === current) continue;

      if (check) {
        stale.push(relative(root, markdownPath));
      } else {
        writeFileSync(markdownPath, markdown);
        console.log(`Wrote ${relative(root, markdownPath)}`);
      }
    }

    if (!generated) {
      console.log('No IO stories declare `parameters.docs.usage`.');
    }
    const orphans = generatedFiles().filter((path) => !outputs.includes(path));
    for (const path of orphans) {
      if (check) {
        stale.push(`${path} (its component no longer declares usage)`);
      } else {
        rmSync(join(root, path));
        console.log(`Removed ${path}`);
      }
    }

    if (stage && !check && outputs.length) {
      execFileSync('git', ['add', '--', ...outputs], { cwd: root });
    }
    if (stage && orphans.length && !check) {
      execFileSync(
        'git',
        ['rm', '--cached', '--ignore-unmatch', '--quiet', '--', ...orphans],
        { cwd: root },
      );
    }
    if (stale.length) {
      throw new Error(
        `Out of date: ${stale.join(', ')}. Run \`pnpm stories:generate-docs\`.`,
      );
    }
  } finally {
    await browser.close();
    server.close();
  }
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
